_EXT_TO_ASSIMP_FORMAT = {
    "dae": "collada",
    "glb": "glb2",
    "gltf": "gltf2",
    "stl": "stlb",
}


async def convert(input_path: Path, output_path: Path) -> Path:
    ext = output_path.suffix.lstrip(".")
    fmt_id = _EXT_TO_ASSIMP_FORMAT.get(ext, ext)
    args = ["assimp", "export", str(input_path), str(output_path), f"-f{fmt_id}"]
    await run_subprocess(*args)
    return output_path
